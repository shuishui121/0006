export const getHint = (roomType: string, hintLevel: number): string | null => {
  const hints = ROOM_HINTS[roomType];
  if (!hints || hintLevel < 0 || hintLevel >= hints.length) return null;
  return hints[hintLevel];
};

export const getMaxHints = (roomType: string): number => {
  return ROOM_HINTS[roomType]?.length || 0;
};
